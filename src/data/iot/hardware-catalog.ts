// Helper functions for BOM queries without duplicate counting
export function getHardwarePart(partId: string): HardwarePart | undefined {
  return HARDWARE_CATALOG.find((p) => p.partId === partId);
}

export function getLessonBOM(lessonSlug: string): HardwarePart[] {
  return HARDWARE_CATALOG.filter((p) => p.relatedLessonSlugs.includes(lessonSlug));
}

export function getKitSummary(tier?: 'basic' | 'intermediate' | 'advanced') {
  const parts = tier ? HARDWARE_CATALOG.filter((p) => p.kitTier === tier) : HARDWARE_CATALOG;
  return {
    totalParts: parts.length,
    requiredCount: parts.filter((p) => p.required).length,
    optionalCount: parts.filter((p) => p.optional).length,
    parts,
  };
}
